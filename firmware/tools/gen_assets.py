"""Generate src/assets.{h,cpp}: the service's pixel fonts and the status icons as C tables.

The fonts are the same text files the service and the emulator draw with
(service/assets/fonts/pixel), so the clock looks the same everywhere (§10).
The MDI icons are rendered at the emulator's size and cut at 50 % like it does.

Run with the service venv (it has Pillow):
    service/.venv/bin/python firmware/tools/gen_assets.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
PIXEL = ROOT / "service/assets/fonts/pixel"
MDI_TTF = ROOT / "service/assets/mdi/materialdesignicons-webfont.ttf"
OUT = ROOT / "firmware/src"

FONTS = {  # C name: pixel font file
    "FONT_CLOCK": "clock-64",
    "FONT_DATE": "Inter-Medium-16",
    "FONT_SEMI16": "Inter-SemiBold-16",
    "FONT_SEMI30": "Inter-SemiBold-30",
}

ICON_SIZE = 17  # px, as the emulator's status bar
ICONS = {
    "ICON_WIFI": 0xF0925,
    "ICON_WIFI_OFF": 0xF092E,
    "ICON_CLOUD": 0xF0163,
    "ICON_CLOUD_OFF": 0xF0164,
    "ICON_HOME": 0xF06A1,
    "ICON_HOME_OFF": 0xF1A47,
    "ICON_DATA_OFF": 0xF1640,
}


def parse_pixel_font(path: Path) -> dict:
    """Same format as parsePixelFont in the emulator: header, then 'glyph <hex>', fields, rows."""
    lines = path.read_text().split("\n")
    font = {"ascent": 0, "descent": 0, "glyphs": []}
    i = 0
    while i < len(lines) and not lines[i].startswith("glyph "):
        parts = lines[i].split(" ")
        if parts[0] in ("ascent", "descent"):
            font[parts[0]] = int(parts[1])
        i += 1
    while i < len(lines):
        cp = int(lines[i].split(" ")[1], 16)
        f = lines[i + 1].split(" ")
        fields = {f[j]: int(f[j + 1]) for j in range(0, len(f) - 1, 2)}
        rows = []
        i += 2
        while i < len(lines) and lines[i] and not lines[i].startswith("glyph "):
            rows.append(lines[i])
            i += 1
        font["glyphs"].append({
            "cp": cp, "left": fields["left"], "top": fields["top"], "advance": fields["advance"],
            "rows": [[c == "#" for c in row] for row in rows],
        })
        while i < len(lines) and not lines[i]:
            i += 1
    return font


def icon_font() -> dict:
    """Icons as a font with ascent 0: a glyph's top is relative to the baseline."""
    ttf = ImageFont.truetype(str(MDI_TTF), ICON_SIZE)
    glyphs = []
    for cp in ICONS.values():
        ch = chr(cp)
        l, t, r, b = ttf.getbbox(ch, anchor="ls")
        img = Image.new("L", (r - l, b - t), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=ttf, fill=255, anchor="ls")
        rows = [[img.getpixel((x, y)) >= 128 for x in range(img.width)] for y in range(img.height)]
        glyphs.append({"cp": cp, "left": l, "top": t, "advance": round(ttf.getlength(ch)), "rows": rows})
    return {"ascent": 0, "descent": 0, "glyphs": glyphs}


def pack(rows: list[list[bool]]) -> tuple[int, int, bytes]:
    w = max((len(r) for r in rows), default=0)
    out = bytearray()
    for row in rows:
        for bx in range(0, w, 8):
            byte = 0
            for k in range(8):
                if bx + k < len(row) and row[bx + k]:
                    byte |= 0x80 >> k
            out.append(byte)
    return w, len(rows), bytes(out)


def emit(name: str, font: dict) -> str:
    glyphs = sorted(font["glyphs"], key=lambda g: g["cp"])
    bitmap = bytearray()
    entries = []
    for g in glyphs:
        w, h, data = pack(g["rows"])
        entries.append(f"  {{0x{g['cp']:X}, {len(bitmap)}, {w}, {h}, {g['left']}, {g['top']}, {g['advance']}}},")
        bitmap += data
    hexes = ", ".join(f"0x{b:02X}" for b in bitmap) or "0"
    lo = name.lower()
    return (
        f"static const uint8_t {lo}_bits[] = {{{hexes}}};\n"
        f"static const Glyph {lo}_glyphs[] = {{\n" + "\n".join(entries) + "\n};\n"
        f"const PixFont {name} = {{{font['ascent']}, {font['descent']}, {len(glyphs)}, {lo}_glyphs, {lo}_bits}};\n\n"
    )


def main() -> None:
    header = [
        "// Generated by tools/gen_assets.py — do not edit.",
        "#pragma once",
        '#include "pixfont.h"',
        "",
    ]
    header += [f"extern const PixFont {name};" for name in FONTS]
    header += ["extern const PixFont ICONS;", ""]
    header += [f"constexpr uint32_t {name} = 0x{cp:X};" for name, cp in ICONS.items()]
    body = "// Generated by tools/gen_assets.py — do not edit.\n#include \"assets.h\"\n\n"
    for name, file in FONTS.items():
        body += emit(name, parse_pixel_font(PIXEL / f"{file}.txt"))
    body += emit("ICONS", icon_font())
    (OUT / "assets.h").write_text("\n".join(header) + "\n")
    (OUT / "assets.cpp").write_text(body)
    print(f"wrote {OUT / 'assets.h'} and assets.cpp")


if __name__ == "__main__":
    main()
