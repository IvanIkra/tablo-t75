def icon(d: ImageDraw.ImageDraw, name: str | None, cx: float, cy: float, fill: int = BLACK) -> bool:
    """Draw a 15 px icon centred on (cx, cy); False if there is no pixel version of it."""
    rows = ICONS.get(name or "")
    if rows is None:
        return False
    _put(d, rows, round(cx - ICON / 2), round(cy - ICON / 2), fill)
    return True
