"""Hand-drawn pixel icons (§6.3, §7.4): weather 22 and 44 px, the fixed 15 px icons of the blocks.

At these sizes line drawing or a font glyph in 1 bit gives broken rays, uneven outlines and blobs,
so the icons are pixel grids: "#" black, "." white. Every cloud with rain, snow, a storm or fog is
the same cloud, so the clouds stand on one level whatever falls from them. The 44 px set is the old
line drawings redone pixel by pixel with 3 px strokes; the 15 px set follows the MDI glyphs.
"""

from PIL import ImageDraw

BLACK = 0


def _grid(text: str) -> list[str]:
    return text.strip("\n").splitlines()


def _put(d: ImageDraw.ImageDraw, rows: list[str], x0: int, y0: int, fill: int) -> None:
    points = [(x0 + x, y0 + y) for y, row in enumerate(rows) for x, ch in enumerate(row) if ch == "#"]
    if points:
        d.point(points, fill=fill)


